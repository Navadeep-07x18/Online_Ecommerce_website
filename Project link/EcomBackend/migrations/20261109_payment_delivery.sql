ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS subtotal DECIMAL(12, 2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS delivery_charge DECIMAL(12, 2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS discount DECIMAL(12, 2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS payment_method VARCHAR(20) NOT NULL DEFAULT 'COD',
  ADD COLUMN IF NOT EXISTS payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  ADD COLUMN IF NOT EXISTS delivery_option VARCHAR(20) NOT NULL DEFAULT 'standard',
  ADD COLUMN IF NOT EXISTS checkout_key VARCHAR(100),
  ADD COLUMN IF NOT EXISTS estimated_delivery_start DATE,
  ADD COLUMN IF NOT EXISTS estimated_delivery_date DATE;

UPDATE orders SET subtotal = COALESCE(
  (SELECT SUM(line_total) FROM order_items WHERE order_items.order_id = orders.id), total
) WHERE subtotal = 0;

CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_user_checkout_key
  ON orders (user_id, checkout_key) WHERE checkout_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  payment_method VARCHAR(20) NOT NULL
    CHECK (payment_method IN ('UPI', 'CREDIT_CARD', 'DEBIT_CARD', 'COD')),
  amount DECIMAL(12, 2) NOT NULL CHECK (amount >= 0),
  transaction_reference VARCHAR(40) UNIQUE,
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paid_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_payments_order_created
  ON payments (order_id, created_at DESC);
